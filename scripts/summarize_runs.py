"""Collect finished runs (runs/*/) into one markdown table: cost, dev and test metrics.

python scripts/summarize_runs.py            # prints the table and writes docs/results_table.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from liveness.model import SpoofNet, count_flops, count_params


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="runs")
    parser.add_argument("--out", default="docs/results_table.md")
    args = parser.parse_args()

    header = (
        "| Run | Backbone | Img | Aug | Epochs run | Params M | GMACs | Dev EER (best) "
        "| Test ACER | APCER | BPCER | AUC |\n|---|---|---|---|---|---|---|---|---|---|---|---|"
    )
    lines = [header]
    for run_dir in sorted(Path(args.runs).iterdir()):
        if run_dir.name == "smoke":  # CI pipeline check, not a result
            continue
        history, config = run_dir / "history.json", run_dir / "config.yaml"
        if not (history.is_file() and config.is_file()):
            continue
        cfg = yaml.safe_load(config.read_text())
        hist = json.loads(history.read_text())
        img = cfg["data"]["img_size"]
        model = SpoofNet(**{**cfg["model"], "pretrained": False})
        row = [
            run_dir.name,
            cfg["model"]["name"],
            str(img),
            cfg["data"].get("augment", "full"),
            str(len(hist["history"])),
            f"{count_params(model) / 1e6:.2f}",
            f"{count_flops(model, img) / 2e9:.3f}",
            f"{hist['best']['eer']:.4f} (ep {hist['best']['epoch']})",
        ]
        metrics = run_dir / "metrics_fp32.json"
        if metrics.is_file():
            test = json.loads(metrics.read_text())["test_at_dev_eer_threshold"]
            row += [
                f"{test['acer']:.4f}",
                f"{test['apcer']:.4f}",
                f"{test['bpcer']:.4f}",
                f"{test['auc']:.4f}",
            ]
        else:
            row += ["-", "-", "-", "-"]
        lines.append("| " + " | ".join(row) + " |")

    table = "\n".join(lines)
    print(table)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Results (generated by scripts/summarize_runs.py)\n\n"
        "Test metrics use the threshold chosen on dev. Selection of the final model is by dev EER "
        "and cost, never by test.\n\n" + table + "\n"
    )


if __name__ == "__main__":
    main()
